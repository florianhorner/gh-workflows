#!/usr/bin/env bash
# Baseline editorial patterns for PR bodies, issue bodies and changelogs.
# Sourced by check-body-lint.sh. Consuming repositories may add patterns;
# changing a baseline rule requires a change to this repository.
#
# Patterns match grammatical forms. Add synthetic positive and negative cases
# for each rule, then inspect the matches in lint-pattern-baseline.tsv.
# Corpus source IDs identify numbered synthetic cases.
#
# ---------------------------------------------------------------------------
# DIALECT: POSIX ERE supported by BSD grep on macOS and GNU grep in CI:
#   - no lookahead/lookbehind, no non-capturing groups `(?:...)`, no `\d`,
#     no non-greedy `*?`, no `\K`, no PCRE classes.
#   - `\b` is used; both dialects support it.
# Tests reject grep diagnostics even when grep returns a successful exit code.

# ---------------------------------------------------------------------------
# CORE applies to bodies, changelogs and docs. Check proposed rules against
# the consuming repository's changelog for false positives.
# shellcheck disable=SC2034
LINT_BASELINE_CORE=(
  # References to the tools used to produce a change.
  '/autoplan'
  '\b[Cc]odex (review|independent review)\b'
  '\bClaude (review|Code)\b'
  # Match work done in a workspace; allow documentation of workspace features.
  '\bConductor (session|agent)\b'
  '\b(in|from|on|inside) (this |the |a |my )?Conductor workspace\b'
  '🤖 Generated with'
  '\bCLAUDE\.md\b'

  # Workspace archaeology: local machine state leaking into a public artifact.
  'stash@\{'
  '\b[Uu]n-?pushed branch'
  '\b[Uu]ntracked (code|files)\b'
)

# ---------------------------------------------------------------------------
# BODY applies to PR and issue bodies. Changelogs may contain coverage counts
# and review vocabulary, so these rules do not apply there.
# shellcheck disable=SC2034
LINT_BASELINE_BODY=(
  # R1: a review noun near a past-tense discovery verb. Present-tense
  # descriptions such as "the linter flags a bare except" remain allowed.
  '\b([Rr]eviewers?|[Rr]eview|[Aa]udit|[Mm]utation testing|[Ff]uzzing)\b[^.]{0,40}\b([Ff]ound|[Cc]aught|[Ff]lagged|[Ss]urfaced|[Rr]evealed|[Tt]urned up)\b'

  # R1b: a review actor followed by a progressive verb. Present-tense
  # descriptions without -ing remain allowed.
  '\b[Aa] (reviewer|review pass|reviewer bot) [a-z]+ing\b'

  # R2: a discovery verb before a review noun, such as "found by review".
  '\b([Ff]ound|[Cc]aught|[Ss]urfaced|[Ff]lagged|[Rr]aised)\b[^.]{0,20}\b(by|in|during)\b[^.]{0,15}\b([Rr]eview|[Aa]udit|the reviewer)\b'

  # R3: review headings and summaries. Renaming a heading to "## Notes"
  # bypasses the heading rule; the rule does not inspect the section's content.
  '^#{1,6}[[:space:]]*(Findings|Pre-?Landing Review|Review (notes|findings)|What I (cut|removed|changed))'
  '\bFindings from (review|the review|code review)\b'

  # R4: first-person accounts of how the author arrived at the change.
  '(^|[[:space:]])(What I cut|I should have|I drafted|I rewrote the|I initially)\b'

  # R5: counts of findings, reviewers and review rounds.
  '\b([0-9]+|[Oo]ne|[Tt]wo|[Tt]hree|[Ff]our|[Ff]ive) ([Ff]indings?|[Rr]eview (passes|rounds))\b'
  '\b[0-9]+ of [0-9]+ ([Rr]eviewers|models|agents)\b'
  '\b[Ff]indings (raised|confirmed|refuted|applied)\b'
  '\b[Aa]dversarial(ly)? verif'

  # R6: statements about observed usage and operator preferences, which may
  # disclose private telemetry in public text.
  "\\b([Ss]tation|[Aa]pp|[Pp]roduct|[Ss]ervice)'?s own\\b[^.]{0,30}\\bdata\\b"
  '\b([Uu]sage|[Ll]istening|[Oo]perator preference|[Tt]elemetry) data\b[^.]{0,20}\b([Ss]howed|[Rr]evealed|[Ss]aid|[Rr]ejected|[Cc]onfirmed)\b'
  '\b[Oo]perator preference data\b'

  # R7: one form of unsupported product judgement. Other wording can pass.
  '\b[Nn]obody (had |has )?(chosen|picked|asked for|wanted)\b'
)

# ---------------------------------------------------------------------------
# PROSE_STYLE applies to PR and issue bodies, never changelogs.
# Exempt proof lines so supported syntax such as `n/a — <reason>` remains valid.
# shellcheck disable=SC2034
LINT_BASELINE_PROSE_STYLE=(
  '—'
)

# Lines exempt from PROSE_STYLE. Applied as `grep -vE` before the style pass.
# shellcheck disable=SC2034
LINT_PROSE_STYLE_EXEMPT='n/a[[:space:]]*—|^[[:space:]]*- \[[ x]\]'

# ---------------------------------------------------------------------------
# PLATFORM_FOOTER applies to bodies, never changelogs. check-body-lint.sh
# excludes this exact pair only at the end of a body:
#
#   ---
#   _Generated by [Claude Code](https://claude.ai/code/session_<id>)_
#
# Mid-body text, near-matches and changelogs remain subject to every pattern.
# Bracket expressions keep these regexes compatible with BSD awk and GNU awk.
# shellcheck disable=SC2034
LINT_PLATFORM_FOOTER_RULE='^---$'
# shellcheck disable=SC2034
LINT_PLATFORM_FOOTER_LINE='^_Generated by [[]Claude Code[]][(]https://claude[.]ai/code(/session_[A-Za-z0-9]+)?[)]_$'

# ---------------------------------------------------------------------------
# check-body-lint.sh reports the matching class, avoiding a separate message
# list that could fall out of sync with the patterns.
